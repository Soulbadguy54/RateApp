import { expect, test } from '@playwright/test'

test.use({ serviceWorkers: 'block' })

test('my links: quiet layout, delayed cancellation, long-press bulk delete and nav', async ({ page }) => {
  const nickname = 'links_' + Date.now().toString(36).slice(-8)
  const singleDeletes: string[] = []
  const bulkDeletes: string[] = []
  page.on('request', request => {
    if (request.method() === 'DELETE' && /\/api\/saved-links\/\d+$/.test(request.url())) singleDeletes.push(request.url())
    if (request.method() === 'POST' && request.url().endsWith('/api/saved-links/bulk-delete')) bulkDeletes.push(request.url())
  })

  await page.goto('/')
  await page.getByRole('button', { name: 'Регистрация' }).click()
  await page.locator('input[type=email]').fill(nickname + '@example.com')
  await page.locator('input[autocomplete=username]').fill(nickname)
  await page.locator('input[autocomplete=new-password]').first().fill('29843571')
  await page.locator('input[autocomplete=new-password]').last().fill('29843571')
  await page.getByRole('button', { name: 'Создать аккаунт' }).click()
  await expect(page.locator('.bottom-nav')).toBeVisible()
  const closeInstall = page.getByRole('button', { name: 'Закрыть предложение установки' })
  if (await closeInstall.isVisible()) await closeInstall.click()

  const slot = page.locator('[data-nav-slot="collections"] > button')
  await expect(slot).toContainText('Коллекции')
  const slotRect = await slot.boundingBox()
  if (!slotRect) throw new Error('Grouped nav slot not found')
  await page.mouse.move(slotRect.x + slotRect.width * .75, slotRect.y + slotRect.height / 2)
  await page.mouse.down()
  await page.mouse.move(slotRect.x + slotRect.width * .1, slotRect.y + slotRect.height / 2, { steps: 6 })
  await page.mouse.up()
  await expect(slot).toContainText('Мои ссылки')
  await slot.click()
  await expect(page).toHaveURL(/tab=links/)
  await expect(page.getByRole('heading', { name: 'Мои ссылки' })).toHaveCSS('color', 'rgb(140, 242, 125)')
  await expect(page.getByText('Сохранённые ссылки из других источников')).toBeVisible()
  await expect(page.getByPlaceholder('example.com')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Обновить список ссылок' })).toHaveCount(0)
  await expect(page.getByText('Личная подборка')).toHaveCount(0)
  await expect(page.getByText('Добавь статью, обзор или подборку — всё будет под рукой.')).toBeVisible()

  const addLink = async (address: string) => {
    await page.getByLabel('Добавить ссылку').fill(address)
    await page.getByRole('button', { name: 'Сохранить ссылку' }).click()
  }
  await addLink('example.com/' + nickname + '/one')
  await expect(page.locator('.saved-link-card')).toHaveCount(1)
  await expect(page.locator('.saved-link-card')).toContainText('example.com')
  const trash = page.getByRole('button', { name: /Удалить ссылку/ })
  await trash.click()
  await expect(page.locator('.saved-link-card__countdown line')).toHaveCount(12)
  await expect(page.getByRole('button', { name: /Отменить удаление ссылки/ })).toBeVisible()
  await page.waitForTimeout(750)
  await page.getByRole('button', { name: /Отменить удаление ссылки/ }).click()
  await expect(page.locator('.saved-link-card__countdown')).toHaveCount(0)
  await page.waitForTimeout(4050)
  expect(singleDeletes).toHaveLength(0)
  await expect(page.locator('.saved-link-card')).toHaveCount(1)

  await page.getByRole('button', { name: /Удалить ссылку/ }).click()
  await expect(page.locator('.saved-link-card__countdown')).toBeVisible()
  // The deletion happens only when the time has elapsed; not on first tap.
  expect(singleDeletes).toHaveLength(0)
  await expect(page.locator('.saved-link-card')).toHaveCount(0, { timeout: 9000 })
  expect(singleDeletes).toHaveLength(1)

  await addLink('example.com/' + nickname + '/two')
  await addLink('example.com/' + nickname + '/three')
  await expect(page.locator('.saved-link-card')).toHaveCount(2)
  const firstTitle = page.locator('.saved-link-card').first().locator('h3')
  const rect = await firstTitle.boundingBox()
  if (!rect) throw new Error('Saved link card missing')
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.mouse.down()
  await page.waitForTimeout(530)
  await page.mouse.up()
  await expect(page.getByText('Выбрано: 1')).toBeVisible()
  await expect(page.locator('.saved-link-card__selector')).toHaveCount(2)
  await expect(page.locator('.saved-link-card__selector--checked')).toHaveCount(1)
  await page.locator('.saved-link-card__selector').last().click()
  await expect(page.getByText('Выбрано: 2')).toBeVisible()
  await expect(page.locator('.saved-link-card__selector--checked')).toHaveCount(2)

  await page.getByRole('button', { name: 'Удалить выбранные ссылки: 2' }).click()
  await expect(page.getByRole('alertdialog')).toContainText('Удалить выбранные ссылки (2)?')
  expect(bulkDeletes).toHaveLength(0)
  await page.getByRole('alertdialog').getByRole('button', { name: 'Отмена' }).click()
  expect(bulkDeletes).toHaveLength(0)
  await expect(page.locator('.saved-link-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Удалить выбранные ссылки: 2' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Удалить' }).click()
  await expect(page.locator('.saved-link-card')).toHaveCount(0)
  expect(bulkDeletes).toHaveLength(1)

  await page.goBack()
  await expect(page.locator('.app-exit-toast')).toBeVisible()
  await expect(page).toHaveURL(/tab=links/)
})
